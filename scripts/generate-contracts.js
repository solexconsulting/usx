#!/usr/bin/env node
// Regenerates packages/usx-react/src/contracts.js — the canonical CMS contract
// manifest aggregated from every component's config.json.
// Run: pnpm generate:contracts
import fs from 'node:fs';
import {
  CONTRACTS_PATH,
  buildContractManifest,
  loadComponentConfigs,
  printErrors,
  rel,
} from './lib/component-configs.js';

const { configs, errors } = loadComponentConfigs();
if (errors.size) {
  printErrors(errors);
  console.error(`\nAborted: ${errors.size} config.json file(s) failed validation.`);
  process.exit(1);
}

const manifest = buildContractManifest(configs);

const header = `/*
This file is auto-generated by scripts/generate-contracts.js — do not edit by hand.
Canonical CMS contract manifest (see solex-cms-overview.md), keyed by component
name for O(1) lookup and derived from each component's config.json.
To regenerate: pnpm generate:contracts

Shape: { library, schemaVersion, components: { [componentName]: contract } }.
"schemaVersion" is this manifest's own format version — distinct from each
contract's "version" (that component's config.json version).

A prop with a "component" field (optionally with "omit"/"properties") is a
REFERENCE to another entry in "components", not an inlined copy — look up that
component's entry by name for its full prop set, drop the "omit" names, then
merge this node's own "properties" as overrides/additions.
*/
`;

fs.writeFileSync(CONTRACTS_PATH, `${header}export const componentContracts = ${JSON.stringify(manifest, null, 2)};\n`, 'utf8');
console.log(`Wrote ${configs.size} component contracts to ${rel(CONTRACTS_PATH)}`);

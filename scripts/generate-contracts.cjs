#!/usr/bin/env node
// Aggregates every component's config.json into a single publishable "CMS
// contract" manifest, consumed by the SOLEX CMS (see solex-cms-overview.md).
// Mirrors the packages/tokens/src/theme-manifest.js precedent: one canonical
// JS source of truth, later compiled to JSON by packages/core's build.
const fs = require('fs');
const path = require('path');
const Ajv = require('ajv');

const repoRoot = path.resolve(__dirname, '..');
const componentsDir = path.join(repoRoot, 'packages', 'core', 'src', 'components');
const schemaPath = path.join(repoRoot, 'packages', 'core', 'config.schema.json');
const outPath = path.join(repoRoot, 'packages', 'core', 'src', 'contracts.js');

const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
const ajv = new Ajv({ allErrors: true, allowUnionTypes: true });
const validate = ajv.compile(schema);

const dirs = fs
  .readdirSync(componentsDir, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

// schemaVersion is the format version of this manifest itself (this object's
// own shape), distinct from each component's own "version" field.
const SCHEMA_VERSION = 1;
const components = {};
let failures = 0;

// A prop with "component" (e.g. avatar-group.avatars.items) is NOT expanded
// here — its full shape lives at that component's own top-level contract
// entry. We only keep the reference (component/omit/properties-as-overrides)
// as authored. This is intentional: eagerly inlining referenced props would
// duplicate data across the manifest and risks infinite expansion on a
// circular reference; a flat, top-level-only manifest lets a consumer resolve
// one hop at a time, as deep as it actually needs to go.
for (const dir of dirs) {
  const configPath = path.join(componentsDir, dir, 'config.json');
  if (!fs.existsSync(configPath)) continue;

  const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
  const ok = validate(config);
  if (!ok) {
    failures++;
    console.error(`\nSchema errors in ${path.relative(repoRoot, configPath)}:`);
    validate.errors.forEach((e) => console.error(`  - ${e.instancePath || '/'} ${e.message}`));
    continue;
  }

  components[config.name] = {
    component: config.name,
    version: config.version,
    required: config.required || [],
    props: config.props || {},
  };
}

if (failures) {
  console.error(`\nAborted: ${failures} config.json file(s) failed schema validation.`);
  process.exit(1);
}

const header = `/*
This file is auto-generated by scripts/generate-contracts.cjs — do not edit by hand.
Canonical CMS contract manifest (see solex-cms-overview.md). Keyed by component
name for O(1) lookup, derived from that component's config.json. To regenerate, run:
  node scripts/generate-contracts.cjs

Shape: { library, schemaVersion, components: { [componentName]: contract } }.
"schemaVersion" is this manifest's own format version — distinct from each
contract's own "version" field (that component's config.json version).

A prop with a "component" field (optionally with "omit"/"properties") is a
REFERENCE to another entry in "components", not an inlined copy — look up
that component's own entry by name to get its full prop set, then apply
"omit" (drop those prop names) and merge in this node's own "properties" as
overrides/additions.
*/\n`;

const manifest = {
  library: 'usx',
  schemaVersion: SCHEMA_VERSION,
  components,
};

const body = `export const componentContracts = ${JSON.stringify(manifest, null, 2)};\n`;

fs.writeFileSync(outPath, header + body, 'utf8');
console.log(`Wrote ${Object.keys(components).length} component contracts to ${path.relative(repoRoot, outPath)}`);


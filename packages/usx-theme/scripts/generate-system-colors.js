// generate-system-colors.js — regenerates src/system-colors.generated.js from
// the real USWDS system color token JSON files shipped in
// node_modules/@uswds/uswds/packages/uswds-tokens/colors/*.json.
//
// These are USWDS's immutable "system tokens" (the ~25 color families x
// grades 5-90, plus a parallel "vivid" scale for most families). USX never
// hand-edits these values — this script is the only thing that should ever
// write src/system-colors.generated.js. Re-run it after bumping @uswds/uswds.
//
// Usage: node packages/usx-theme/scripts/generate-system-colors.js

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const uswdsColorsDir = path.join(
  __dirname, '..', '..', '..', 'node_modules', '@uswds', 'uswds',
  'packages', 'uswds-tokens', 'colors'
);
const outFile = path.join(__dirname, '..', 'src', 'system-colors.generated.js');

function parseFamily(json) {
  const prop = json.props[0];
  const grades = {};
  const vivid = {};

  for (const entry of prop.value) {
    if (entry.name === 'vivid') {
      for (const v of entry.value) {
        // A small number of grades have no vivid counterpart and are
        // recorded as `false` in the source JSON rather than being omitted.
        if (typeof v.value === 'string') vivid[v.name] = v.value;
      }
      continue;
    }
    if (typeof entry.value === 'string') grades[entry.name] = entry.value;
  }

  return { grades, vivid };
}

function generate() {
  const files = fs.readdirSync(uswdsColorsDir).filter((f) => f.endsWith('.json'));
  const families = {};

  for (const file of files) {
    const family = file.replace(/\.json$/, '');
    const json = JSON.parse(fs.readFileSync(path.join(uswdsColorsDir, file), 'utf8'));
    families[family] = parseFamily(json);
  }

  const header =
    '// system-colors.generated.js — GENERATED by scripts/generate-system-colors.js\n' +
    '// from node_modules/@uswds/uswds/packages/uswds-tokens/colors/*.json.\n' +
    '// Do not edit by hand; re-run the generator after bumping @uswds/uswds.\n' +
    '//\n' +
    '// Shape: { [family]: { grades: { [grade]: hex }, vivid: { [grade]: hex } } }\n' +
    '// `family` matches the USWDS system-color family name (e.g. "blue-cool").\n' +
    '// `vivid` is empty for families with no vivid scale (e.g. "gray").\n\n';

  const body = `export const systemColors = ${JSON.stringify(families, null, 2)};\n\nexport default systemColors;\n`;

  fs.writeFileSync(outFile, header + body, 'utf8');
  console.log(`Wrote ${Object.keys(families).length} color families to ${path.relative(process.cwd(), outFile)}`);
}

generate();
